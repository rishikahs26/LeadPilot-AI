"use client";

import { useState } from "react";

interface Props {
  leadId: string;
  csId: string;
  initialMessage: string;
  onUpdate: (newMessage: string) => void;
}

export function FollowUpMessage({ leadId, csId, initialMessage, onUpdate }: Props) {
  const [message, setMessage] = useState(initialMessage);
  const [saving, setSaving] = useState(false);
  const [copied, setCopied] = useState(false);
  const [saveError, setSaveError] = useState<string | null>(null);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(message);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Fallback for browsers without clipboard API
      const el = document.createElement("textarea");
      el.value = message;
      document.body.appendChild(el);
      el.select();
      document.execCommand("copy");
      document.body.removeChild(el);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleSave = async () => {
    setSaving(true);
    setSaveError(null);
    try {
      const res = await fetch(`/api/leads/${leadId}/callsense/${csId}`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "update-followup", followUp: message }),
      });
      if (!res.ok) {
        const d = await res.json();
        setSaveError(d.error || "Save failed");
        return;
      }
      onUpdate(message);
    } catch {
      setSaveError("Network error saving message");
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="space-y-3">
      <div className="bg-amber-50 border border-amber-200 rounded-lg p-3 text-xs text-amber-800">
        <strong>Review before sending:</strong> This message was generated by AI. Edit it to remove any claims you haven&apos;t confirmed. Do not invent prices, availability, or possession timelines.
      </div>

      <textarea
        value={message}
        onChange={(e) => setMessage(e.target.value)}
        rows={6}
        className="textarea text-sm"
        aria-label="Follow-up message (editable)"
        maxLength={5000}
      />

      {saveError && <p className="text-red-600 text-xs">{saveError}</p>}

      <div className="flex gap-3">
        <button
          onClick={handleCopy}
          className="btn-secondary text-sm flex items-center gap-2"
          aria-label="Copy follow-up message to clipboard"
        >
          {copied ? "✓ Copied!" : "Copy to Clipboard"}
        </button>
        <button
          onClick={handleSave}
          disabled={saving}
          className="btn-primary text-sm"
        >
          {saving ? "Saving…" : "Save Edits"}
        </button>
      </div>

      <p className="text-xs text-slate-400">
        This message will not be sent automatically. Copy it and send via your preferred channel.
      </p>
    </div>
  );
}
